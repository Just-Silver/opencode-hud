// ─── 先验：点估计 + 置信度，必须成对维护 ───
// 两者来自同一次最小二乘拟合，改动其一必须整体重拟合（不可只改系数表）。
//
// 拟合口径：本机 ~9900 条 assistant 步，特征 = [字母, 数字, 标点, CJK(汉字+全角), 工具调用次数]，
// 目标是该步的 tokens.output + tokens.reasoning。空白不计（BPE 并入相邻 token，拟合系数为负）。
// 复现方法见 docs/design-performance-footer.md §7.3。
//
// 协方差 = (XᵀX)⁻¹·σ̂²·PRIOR_INFLATION²
//   σ̂² = 4859.7（单步残差方差，σ̂ ≈ 70 token）
//   PRIOR_INFLATION 见下。
//
// 注意矩阵是满阵而非对角阵：`字母` 与 `标点` 的相关系数为 **-0.90**（此消彼长）。
// 只保留对角线会把这种耦合当成两个独立误差，滤波器在正交方向反复横跳。

// 先验的膨胀系数 = 8，含义是「先验折合约 1180 条等效样本」：
//   · 单位说明：SE 度量的是先验在**旧数据上**的采样误差；膨胀对冲的是**旧数据之外**
//     的不确定性（换模型、流量构成漂移），两者不是同一把尺子，故用等效样本数表达。
//   · 取值依据：实测安全区间为 [×4, ×16]（×4 起能学但迁移停滞，×16 在不伤验证上已劣化），
//     几何中点恰为 ×8 —— 离两种失败模式等距。
//   · 失败不对称：膨胀过小的失败是静默的（MAPE 正常但适应机制已瘫痪）；膨胀过大会立刻
//     在「不伤验证」里显形。选边时站可被观测到的一侧。
//   · **不要调到 ×16**：已实测出界（不伤验证劣化、R=1 噪声模型下 MAPE 8.1% 贴边）。
